// Command landgrid writes land_grid.go, the land the exit map draws as
// dots: one bit per 1° cell, from Natural Earth's 1:110m land (public
// domain) as world-atlas packs it in TopoJSON:
//
//	curl -sSfLo land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json
//	go run ./scripts/landgrid land-110m.json > land_grid.go
//
// A cell is land if any of 3×3 points in it is, so that small islands
// (Taiwan, Singapore) keep a dot.
package main

import (
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

const step = 1 // degree per cell

type topology struct {
	Transform struct {
		Scale     [2]float64 `json:"scale"`
		Translate [2]float64 `json:"translate"`
	} `json:"transform"`
	Arcs    [][][2]float64 `json:"arcs"`
	Objects struct {
		Land struct {
			Geometries []struct {
				Type string          `json:"type"`
				Arcs json.RawMessage `json:"arcs"`
			} `json:"geometries"`
		} `json:"land"`
	} `json:"objects"`
}

type pt struct{ lon, lat float64 }

func main() {
	b, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var t topology
	if err := json.Unmarshal(b, &t); err != nil {
		fail(err)
	}
	// Arcs, quantized and delta-encoded.
	arcs := make([][]pt, len(t.Arcs))
	for i, a := range t.Arcs {
		var x, y float64
		for _, d := range a {
			x, y = x+d[0], y+d[1]
			arcs[i] = append(arcs[i], pt{x*t.Transform.Scale[0] + t.Transform.Translate[0], y*t.Transform.Scale[1] + t.Transform.Translate[1]})
		}
	}
	ring := func(ids []int) []pt {
		var r []pt
		for _, id := range ids {
			a := arcs[id]
			if id < 0 {
				a = reversed(arcs[^id])
			}
			if len(r) > 0 {
				a = a[1:]
			}
			r = append(r, a...)
		}
		return r
	}
	var rings [][]pt // even-odd: holes cancel
	for _, g := range t.Objects.Land.Geometries {
		var polys [][][]int
		switch g.Type {
		case "Polygon":
			var p [][]int
			must(json.Unmarshal(g.Arcs, &p))
			polys = [][][]int{p}
		case "MultiPolygon":
			must(json.Unmarshal(g.Arcs, &polys))
		}
		for _, p := range polys {
			for _, r := range p {
				rings = append(rings, unwrap(ring(r)))
			}
		}
	}
	inside := func(r []pt, lon, lat float64) bool {
		in := false
		for i, j := 0, len(r)-1; i < len(r); j, i = i, i+1 {
			a, b := r[i], r[j]
			if (a.lat > lat) != (b.lat > lat) && lon < (b.lon-a.lon)*(lat-a.lat)/(b.lat-a.lat)+a.lon {
				in = !in
			}
		}
		return in
	}
	land := func(lon, lat float64) bool {
		in := false
		for _, r := range rings {
			// An unwrapped ring may reach past ±180°.
			if inside(r, lon, lat) || inside(r, lon-360, lat) || inside(r, lon+360, lat) {
				in = !in
			}
		}
		return in
	}
	cols, rows := 360/step, 180/step
	bits := make([]byte, (cols*rows+7)/8)
	n := 0
	for row := range rows {
		lat0 := 90 - float64(row+1)*step
		for col := range cols {
			lon0 := -180 + float64(col)*step
			hit := false
			for k := 0; k < 9 && !hit; k++ {
				hit = land(lon0+step*(float64(k%3)+.5)/3, lat0+step*(float64(k/3)+.5)/3)
			}
			if hit {
				i := row*cols + col
				bits[i/8] |= 1 << (i % 8)
				n++
			}
		}
	}
	enc := base64.StdEncoding.EncodeToString(bits)
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by scripts/landgrid from Natural Earth 1:110m land; DO NOT EDIT.\n\n")
	fmt.Fprintf(&sb, "package main\n\n")
	fmt.Fprintf(&sb, "// landGrid is the land, one bit per %d° cell (%d land of %d), row by row\n", step, n, cols*rows)
	fmt.Fprintf(&sb, "// from 90°N and 180°W, low bit first, in base64.\n")
	fmt.Fprintf(&sb, "const (\n\tlandStep = %d\n\tlandGrid = \"\" +\n", step)
	for i := 0; i < len(enc); i += 96 {
		end := min(i+96, len(enc))
		sep := " +"
		if end == len(enc) {
			sep = ""
		}
		fmt.Fprintf(&sb, "\t\t%q%s\n", enc[i:end], sep)
	}
	sb.WriteString(")\n")
	os.Stdout.WriteString(sb.String())
}

// unwrap makes a ring's longitudes continuous: a ring across the
// antimeridian (Fiji, Chukotka) would otherwise jump from +180° to -180°
// and cut through every point on its way.
func unwrap(r []pt) []pt {
	for i := 1; i < len(r); i++ {
		for r[i].lon-r[i-1].lon > 180 {
			r[i].lon -= 360
		}
		for r[i].lon-r[i-1].lon < -180 {
			r[i].lon += 360
		}
	}
	return r
}

func reversed(a []pt) []pt {
	r := make([]pt, len(a))
	for i, p := range a {
		r[len(a)-1-i] = p
	}
	return r
}

func must(err error) {
	if err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "landgrid:", err)
	os.Exit(1)
}
