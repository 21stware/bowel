package i18n

// The strings of rules for an application (routes.KindApp), kept apart from
// the main tables so that work on other parts merges cleanly.

func init() {
	for k, v := range jaAppRules {
		jaTable[k] = v
	}
	for k, v := range hantAppRules {
		hantTable[k] = v
	}
}

