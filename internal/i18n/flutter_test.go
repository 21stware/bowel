//go:generate go test -count=1 -run ^TestFlutterTable$ -update

var update = flag.Bool("update", false, "write the Flutter app's table instead of checking it")

// flutterTable is the Flutter app's table, from the repository's root.
const flutterTable = "mobile/flutter/lib/app/i18n_tables.dart"

// flutterPair finds the Chinese of a tr call as the app's own test does
// (mobile/flutter/test/i18n_test.dart), which keeps it a literal.
var flutterPair = regexp.MustCompile(`\btr\(\s*'((?:[^'\\]|\\.)*)'`)

// TestFlutterTable: the Flutter app's table has Japanese and Traditional
// for every tr in the app and for nothing else, in the desktop's words
// where the desktop has the string and flutter.go does not override them.
// go generate writes it.
func TestFlutterTable(t *testing.T) {
	root, _ := filepath.Abs("../..")
	keys := flutterKeys(t, filepath.Join(root, "mobile", "flutter", "lib"))
	var b strings.Builder
	b.WriteString(`// Generated by go generate ./internal/i18n. Do not edit.
//
// The other languages of ` + "`tr`" + `, keyed by its Chinese, for each tr in lib:
// the desktop's translations (internal/i18n) where it has the string, and
// the app's own from internal/i18n/flutter.go.
`)
	for _, l := range []struct {
		lang                    string
		desktop, only, override map[string]string
	}{
		{"ja", jaTable, jaFlutter, jaFlutterOverride},
		{"hant", hantTable, hantFlutter, hantFlutterOverride},
	} {
		words := flutterWords(t, l.lang, keys, l.desktop, l.only, l.override)
		fmt.Fprintf(&b, "\nconst %sTable = <String, String>{\n", l.lang)
		for _, k := range keys {
			fmt.Fprintf(&b, "  %s: %s,\n", dartgen.Quote(k), dartgen.Quote(words[k]))
		}
		b.WriteString("};\n")
	}
	if t.Failed() {
		return
	}
	if err := dartgen.Sync(filepath.Join(root, flutterTable), b.String(), *update, "go generate ./internal/i18n"); err != nil {
		t.Fatal(err)
	}
}

// flutterKeys are the Chinese of the app's tr calls in lib, sorted.
func flutterKeys(t *testing.T, lib string) []string {
	seen := map[string]bool{}
	err := filepath.WalkDir(lib, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".dart") || d.Name() == filepath.Base(flutterTable) {
			return err
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, m := range flutterPair.FindAllStringSubmatch(string(b), -1) {
			k, err := dartgen.Unquote(m[1])
			if err != nil {
				t.Errorf("%s: %v", path, err)
				continue
			}
			seen[k] = true
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(seen) == 0 {
		t.Fatalf("no tr in %s", lib)
	}
	return slices.Sorted(maps.Keys(seen))
}

// flutterWords is one language's words for each of keys: the override's,
// the app's own, or the desktop's, with its verbs as the app's slots.
func flutterWords(t *testing.T, lang string, keys []string, desktop, only, override map[string]string) map[string]string {
	// The desktop's strings as the app spells them. Two that spell the
	// same, as %s and %d would, must say the same.
	ours := map[string]string{}
	from := map[string][]string{}
	unlike := map[string]bool{}
	for _, zh := range slices.Sorted(maps.Keys(desktop)) {
		k, s := dartSlots(zh), dartSlots(desktop[zh])
		if prev, ok := ours[k]; ok && prev != s {
			unlike[k] = true
		}
		ours[k] = s
		from[k] = append(from[k], zh)
	}
	onlyName, overrideName := lang+"Flutter", lang+"FlutterOverride"
	words := map[string]string{}
	for _, k := range keys {
		desk, has := ours[k]
		if _, ok := override[k]; unlike[k] && !ok {
			t.Errorf("%s: the desktop's %q read the same in the app but are not translated alike: put the app's words in %s", lang, from[k], overrideName)
		}
		if s, ok := override[k]; ok {
			switch {
			case !has:
				t.Errorf("%s: the desktop no longer has %q: move it from %s to %s", lang, k, overrideName, onlyName)
			case s == desk:
				t.Errorf("%s: %s has the desktop's own words for %q: drop it", lang, overrideName, k)
			}
			words[k] = s
		} else if s, ok := only[k]; ok {
			if has {
				t.Errorf("%s: the desktop has %q now, as %q: drop it from %s, or move it to %s if the app means something else by it", lang, k, desk, onlyName, overrideName)
			}
			words[k] = s
		} else if has {
			words[k] = desk
		} else {
			t.Errorf("%s lacks %q, which the app asks for: add it to %s (internal/i18n/flutter.go)", lang, k, onlyName)
			continue
		}
		if !slices.Equal(flutterSlots(k), flutterSlots(words[k])) {
			t.Errorf("%s: %q fills %v, its translation %q %v", lang, k, flutterSlots(k), words[k], flutterSlots(words[k]))
		}
	}
	for name, m := range map[string]map[string]string{onlyName: only, overrideName: override} {
		for k := range m {
			if !slices.Contains(keys, k) {
				t.Errorf("%s: no tr in the app asks for %q any more: drop it from %s", lang, k, name)
			}
		}
	}
	return words
}

var (
	goVerb = regexp.MustCompile(`%(?:\[(\d+)\])?[-+# 0]*\d*(?:\.\d+)?[a-zA-Z%]`)
	slot   = regexp.MustCompile(`\{\d+\}`)
)

// dartSlots is s with its format verbs as the app's tr fills them in:
// each %s or %d the next of {0}, {1}…, %[2]s {1}, and %% a percent sign.
func dartSlots(s string) string {
	n := 0
	return goVerb.ReplaceAllStringFunc(s, func(v string) string {
		if strings.HasSuffix(v, "%") {
			return "%"
		}
		if m := goVerb.FindStringSubmatch(v); m[1] != "" {
			n, _ = strconv.Atoi(m[1])
			n--
		}
		n++
		return "{" + strconv.Itoa(n-1) + "}"
	})
}

// flutterSlots are the slots s fills, sorted and each once.
func flutterSlots(s string) []string {
	return slices.Compact(slices.Sorted(slices.Values(slot.FindAllString(s, -1))))
}
