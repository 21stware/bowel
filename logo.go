// strokeLogo paints the line through pts (logoPoints or a tail of it) into
// cov, a w by h coverage map, with round caps and joins, at scale pixels
// per unit, its box's corner at (ox, oy), width units wide.
// Each pixel keeps the most coverage of any segment, so the overlaps of a
// round join do not darken.
func strokeLogo(pts, cov []float64, w, h int, scale, ox, oy, width float64) {
	r := width * scale / 2
	for i := 0; i+3 < len(pts); i += 2 {
		ax, ay := ox+pts[i]*scale, oy+pts[i+1]*scale
		bx, by := ox+pts[i+2]*scale, oy+pts[i+3]*scale
		x0, x1 := int(math.Floor(math.Min(ax, bx)-r-1)), int(math.Ceil(math.Max(ax, bx)+r+1))
		y0, y1 := int(math.Floor(math.Min(ay, by)-r-1)), int(math.Ceil(math.Max(ay, by)+r+1))
		dx, dy := bx-ax, by-ay
		ll := dx*dx + dy*dy
		for y := max(y0, 0); y <= min(y1, h-1); y++ {
			for x := max(x0, 0); x <= min(x1, w-1); x++ {
				// The pixel's center's distance to the segment.
				px, py := float64(x)+.5-ax, float64(y)+.5-ay
				t := 0.0
				if ll > 0 {
					t = math.Max(0, math.Min(1, (px*dx+py*dy)/ll))
				}
				d := math.Hypot(px-t*dx, py-t*dy)
				if c := math.Max(0, math.Min(1, r-d+.5)); c > cov[y*w+x] {
					cov[y*w+x] = c
				}
			}
		}
	}
}

// appIcon draws the app's icon, n by n pixels: the spiral in fg on a
// rounded square of bg, inset as macOS's icon grid has it (824 of 1024).
func appIcon(n int, bg, fg color.NRGBA) []byte {
	img := image.NewNRGBA(image.Rect(0, 0, n, n))
	s := float64(n) / 1024
	side, rad := 824*s, 185*s
	tile := make([]float64, n*n)
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			// Coverage of the rounded square: distance to its inner box.
			px, py := float64(x)+.5, float64(y)+.5
			qx := math.Max(math.Abs(px-float64(n)/2)-(side/2-rad), 0)
			qy := math.Max(math.Abs(py-float64(n)/2)-(side/2-rad), 0)
			tile[y*n+x] = math.Max(0, math.Min(1, rad-math.Hypot(qx, qy)+.5))
		}
	}
	mark := make([]float64, n*n)
	// The spiral fills 78% of the tile, as the design's app icon.
	scale := side * .78 / 200
	o := float64(n)/2 - 100*scale
	strokeLogo(logoPoints, mark, n, n, scale, o, o, logoWidth)
	for i, t := range tile {
		if t == 0 {
			continue
		}
		m := mark[i]
		mix := func(a, b uint8) uint8 { return uint8(math.Round(float64(a)*(1-m) + float64(b)*m)) }
		img.Pix[i*4+0] = mix(bg.R, fg.R)
		img.Pix[i*4+1] = mix(bg.G, fg.G)
		img.Pix[i*4+2] = mix(bg.B, fg.B)
		img.Pix[i*4+3] = uint8(math.Round(t * 255))
	}
	var buf bytes.Buffer
	_ = png.Encode(&buf, img)
	return buf.Bytes()
}
