// strokeLogo paints the line through pts (logoPoints) into
// cov, a w by h coverage map, with round caps and joins, at scale pixels
// per unit, its box's corner at (ox, oy), width units wide.
// Each pixel keeps the most coverage of any segment, so the overlaps of a
// round join do not darken.
func strokeLogo(pts, cov []float64, w, h int, scale, ox, oy, width float64) {
	r := width * scale / 2
	for i := 0; i+3 < len(pts); i += 2 {
		ax, ay := ox+pts[i]*scale, oy+pts[i+1]*scale
		bx, by := ox+pts[i+2]*scale, oy+pts[i+3]*scale
		x0, x1 := int(math.Floor(math.Min(ax, bx)-r-1)), int(math.Ceil(math.Max(ax, bx)+r+1))
		y0, y1 := int(math.Floor(math.Min(ay, by)-r-1)), int(math.Ceil(math.Max(ay, by)+r+1))
		dx, dy := bx-ax, by-ay
		ll := dx*dx + dy*dy
		for y := max(y0, 0); y <= min(y1, h-1); y++ {
			for x := max(x0, 0); x <= min(x1, w-1); x++ {
				// The pixel's center's distance to the segment.
				px, py := float64(x)+.5-ax, float64(y)+.5-ay
				t := 0.0
				if ll > 0 {
					t = math.Max(0, math.Min(1, (px*dx+py*dy)/ll))
				}
				d := math.Hypot(px-t*dx, py-t*dy)
				if c := math.Max(0, math.Min(1, r-d+.5)); c > cov[y*w+x] {
					cov[y*w+x] = c
				}
			}
		}
	}
}
