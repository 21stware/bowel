//go:generate go test -count=1 -run ^TestFlutterSkins$ -update

var update = flag.Bool("update", false, "write the Flutter app's skins instead of checking them")

// flutterSkins are the skins the Flutter app offers; it lists them in
// skins' order. One added here wants its texture in
// mobile/flutter/lib/pages/deco.dart.
var flutterSkins = []string{"paper", "broadsheet", "phosphor", "neon", "blueprint", "sakura"}

// flutterRoutes are the routes a palette colors, in the app's order
// (routeIds in mobile/flutter/lib/ui/skin.dart).
var flutterRoutes = []string{"default", "ai", "media", "dev", "direct"}

// TestFlutterSkins: the Flutter app's skins and their names
// (mobile/flutter/lib/ui/skin_data.dart) are the desktop's. go generate
// writes them.
func TestFlutterSkins(t *testing.T) {
	const path = "mobile/flutter/lib/ui/skin_data.dart"
	src, err := os.ReadFile("mobile/flutter/lib/ui/skin.dart")
	if err != nil {
		t.Fatal(err)
	}
	quoted := make([]string, len(flutterRoutes))
	for i, r := range flutterRoutes {
		quoted[i] = dartgen.Quote(r)
	}
	if want := "const routeIds = [" + strings.Join(quoted, ", ") + "];"; !strings.Contains(string(src), want) {
		t.Errorf("skin.dart has no %s", want)
	}

	var defs, names strings.Builder
	n := 0
	for i := range skins {
		k := &skins[i]
		if !slices.Contains(flutterSkins, k.id) {
			continue
		}
		n++
		// The app keeps one face, corners and glow for both palettes.
		p := k.light
		if p == nil {
			p = k.dark
		}
		if l, d := k.light, k.dark; l != nil && d != nil &&
			(l.font != d.font || l.display != d.display || l.round != d.round || dartColor(l.glow) != dartColor(d.glow)) {
			t.Errorf("%s: its palettes differ in faces, corners or glow, which the app has one of", k.id)
		}
		accentL := "null"
		if k.light != nil {
			accentL = dartColor(ui.Hex(accentHex(k.accent, false)))
		}
		glow := "null"
		if p.glow.A > 0 {
			glow = dartColor(p.glow)
		}
		fmt.Fprintf(&defs, "  %s: SkinDef(\n", dartgen.Quote(k.id))
		fmt.Fprintf(&defs, "    name: %s,\n", dartgen.Quote(k.zh))
		fmt.Fprintf(&defs, "    accentL: %s,\n", accentL)
		fmt.Fprintf(&defs, "    accentD: %s,\n", dartColor(ui.Hex(accentHex(k.accent, true))))
		fmt.Fprintf(&defs, "    light: %s,\n", dartPalette(t, k.id, k.light))
		fmt.Fprintf(&defs, "    dark: %s,\n", dartPalette(t, k.id, k.dark))
		fmt.Fprintf(&defs, "    font: %s,\n", dartgen.Quote(dartFace(p.font)))
		fmt.Fprintf(&defs, "    disp: %s,\n", dartgen.Quote(dartFace(p.display)))
		fmt.Fprintf(&defs, "    round: %s,\n", strconv.FormatFloat(float64(p.round), 'f', -1, 32))
		fmt.Fprintf(&defs, "    glow: %s,\n", glow)
		defs.WriteString("  ),\n")
		fmt.Fprintf(&names, "      %s => tr(%s, %s),\n", dartgen.Quote(k.id), dartgen.Quote(k.zh), dartgen.Quote(k.en))
	}
	if n != len(flutterSkins) {
		t.Errorf("flutterSkins %v names a skin there is not", flutterSkins)
	}
	if t.Failed() {
		return
	}
	out := `// Generated by go generate . from skins.go and ui.go (flutter_skins_test.go).
// Do not edit.
import 'dart:ui';

import '../app/i18n.dart';
import 'skin.dart';

const skinDefs = <String, SkinDef>{
` + defs.String() + `};

/// A skin's name in the interface's language; ` + "`skinDefs`" + ` holds the Chinese.
String skinName(String id) => switch (id) {
` + names.String() + `      _ => id,
    };
`
	if err := dartgen.Sync(path, out, *update, "go generate ."); err != nil {
		t.Fatal(err)
	}
}

// dartPalette is p as the app's Palette, "null" for none. On the phone a
// dark palette's paper2 is its sheet, as prototype/mobile.html made it when
// the app was drawn.
func dartPalette(t *testing.T, id string, p *pal) string {
	if p == nil {
		return "null"
	}
	paper2 := p.paper2
	if p.dark {
		paper2 = p.sheet
	}
	routes := make([]string, len(flutterRoutes))
	for i, r := range flutterRoutes {
		c, ok := p.route[r]
		if !ok {
			t.Errorf("%s: a palette has no color for route %s", id, r)
		}
		routes[i] = dartColor(c)
	}
	return fmt.Sprintf("Palette(paper: %s, paper2: %s, card: %s, sheet: %s, ink: %s, ink2: %s, mute: %s, faint: %s, hair: %s, hair2: %s, hover: %s, signal: %s, good: %s, warn: %s, routes: [%s])",
		dartColor(p.paper), dartColor(paper2), dartColor(p.card), dartColor(p.sheet),
		dartColor(p.ink), dartColor(p.ink2), dartColor(p.mute), dartColor(p.faint),
		dartColor(p.hair), dartColor(p.hair2), dartColor(p.hover),
		dartColor(p.signal), dartColor(p.good), dartColor(p.warn), strings.Join(routes, ", "))
}

func dartColor(c ui.Color) string {
	return fmt.Sprintf("Color(0x%02X%02X%02X%02X)", c.A, c.R, c.G, c.B)
}

// dartFace is the family the app sets a face of the desktop's in: its first
// that the app can name. The app bundles OPPO Sans as "OPPO Sans"; SF Mono
// is the Mac's own, so a monospace starts at Menlo.
func dartFace(face string) string {
	for f := range strings.SplitSeq(face, ",") {
		switch f = strings.TrimSpace(f); f {
		case "SF Mono":
		case "OPPO Sans 4.0":
			return "OPPO Sans"
		default:
			return f
		}
	}
	return ""
}
